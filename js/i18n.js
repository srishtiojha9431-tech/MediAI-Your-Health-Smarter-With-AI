// =====================================================
// CHANGE LANGUAGE
// =====================================================

function changeLanguage(language) {

    const dictionary = translations[language];

    if (!dictionary) {

        console.error(
            "Language not found:",
            language
        );

        return;
    }


    // Translate normal text

    document
        .querySelectorAll("[data-i18n]")
        .forEach(function(element) {

            const key =
                element.getAttribute("data-i18n");

            if (dictionary[key]) {

                element.textContent =
                    dictionary[key];

            }

        });


    // Translate placeholders

    document
        .querySelectorAll("[data-i18n-placeholder]")
        .forEach(function(element) {

            const key =
                element.getAttribute(
                    "data-i18n-placeholder"
                );

            if (dictionary[key]) {

                element.placeholder =
                    dictionary[key];

            }

        });


    // Save language

    localStorage.setItem(
        "mediAI-language",
        language
    );


    // Update HTML language

    document.documentElement.lang =
        language;


    console.log(
        "Medi AI language changed to:",
        language
    );

}


// =====================================================
// PAGE LOAD
// =====================================================

document.addEventListener(
    "DOMContentLoaded",
    function() {

        const languageSelect =
            document.getElementById(
                "languageSelect"
            );


        // Get saved language

        const savedLanguage =
            localStorage.getItem(
                "mediAI-language"
            ) || "en";


        // Set dropdown

        if (languageSelect) {

            languageSelect.value =
                savedLanguage;

        }


        // Apply language

        changeLanguage(
            savedLanguage
        );


        // Listen for language changes

        if (languageSelect) {

            languageSelect.addEventListener(
                "change",
                function() {

                    changeLanguage(
                        this.value
                    );

                }
            );

        }

    }
);